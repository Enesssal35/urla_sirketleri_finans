function calculateMagicFormula(stocks) {
    return [...stocks].sort((a, b) => {
        const scoreA = (a.metrics.roic * 0.6) + ((1 / a.metrics.peRatio) * 100 * 0.4);
        const scoreB = (b.metrics.roic * 0.6) + ((1 / b.metrics.peRatio) * 100 * 0.4);
        return scoreB - scoreA;
    });
}

function addNewQuarterData(stockCode, quarterLabel, roe, roic, wacc, revenue = 0) {
    const stock = BIST_STOCKS.find(s => s.code === stockCode);
    if (stock) {
        stock.historical8Q.push({
            quarter: quarterLabel,
            roe: roe,
            roic: roic,
            wacc: wacc,
            nopat: Math.round(revenue * (roic / 100.0) * 0.45),
            netIncome: Math.round(revenue * (roe / 100.0) * 0.35),
            revenue: revenue
        });
        stock.metrics.roe = roe;
        stock.metrics.roic = roic;
        stock.metrics.wacc = wacc;
    }
}
